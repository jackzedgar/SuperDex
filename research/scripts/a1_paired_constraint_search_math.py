OPTIMIZATION_SEEDS=(280043,280044)
DEVELOPMENT_SEEDS=(280046,280047,280048,280049)
POPULATION=32
MAX_GENERATIONS=12
TOTAL_PROCESS_SECONDS=3240

def active_mask(mask):
    a=np.asarray(mask,dtype=np.float64)
    if a.shape!=(2,) or not np.isin(a,[0,1]).all() or not a.any():raise ValueError('Expected the original nonempty two-hand binary mask')
    return a.astype(bool)

def normalized_error(row,mask):
    active=active_mask(mask);e=np.asarray(row['mean_errors'],dtype=np.float64)
    if e.shape!=(6,) or not np.isfinite(e).all() or (e<0).any():raise ValueError('Invalid original error vector')
    return float(max(e[0]/.03,e[1]/(np.pi/6),np.max(e[2:4][active]/.08),np.max(e[4:6][active]/.06)))

def paired_rank(rows,horizon,mask):
    if len(rows)!=2 or {r['seed'] for r in rows}!=set(OPTIMIZATION_SEEDS):raise ValueError('Exactly the two optimization seeds are required')
    if not isinstance(horizon,int) or horizon<=33:raise ValueError('Unregistered horizon')
    for r in rows:
        if not r['complete'] or r['status'] not in ('original_termination','reference_end'):raise ValueError('Budget truncation is not a complete search condition')
        n=r['controls']
        if not isinstance(n,int) or not 0<n<=horizon:raise ValueError('Invalid control count')
        if r['status']=='reference_end' and (n!=horizon or r['failure_reason']!=0):raise ValueError('Reference end must match the original terminal state')
        if r['phase_start']!=0 or r['reset_memory']!='original':raise ValueError('Frozen initialization differs')
        if not isinstance(r['regular_success'],bool) or not isinstance(r['strict_success'],bool):raise ValueError('Invalid success flags')
        if r['strict_success'] and not r['regular_success']:raise ValueError('Strict success must also be regular')
        if r['regular_success'] and (n!=horizon or r['failure_reason']!=0):raise ValueError('A prefix or physical failure cannot be successful')
        if r['failure_reason'] not in [0,1,2,3,4] or not np.isfinite(r['return_sum']):raise ValueError('Invalid original condition')
    # The environment's existing success flags remain authoritative. Error
    # normalization is used only as a search tie-breaker,never as relabeling.
    reg=[int(r['regular_success']) for r in rows];strict=[int(r['strict_success']) for r in rows]
    errors=[normalized_error(r,mask) for r in rows]
    return (min(reg),sum(reg)/2,min(strict),sum(strict)/2,min(r['controls']/horizon for r in rows),-max(errors),-sum(errors)/2,sum(r['return_sum'] for r in rows)/2)

def pair_generation(population,rows,horizon,mask,generation):
    p=np.asarray(population);active=np.repeat(active_mask(mask),26)
    if p.shape!=(POPULATION,4,52) or not np.isfinite(p).all() or abs(p).max()>2 or (p*(1-active)).any():raise ValueError('Unregistered candidate population')
    if not isinstance(generation,int) or not 0<=generation<MAX_GENERATIONS or len(rows)!=POPULATION*2:raise ValueError('Incomplete or excess generation')
    indexed={}
    for row in rows:
        i=row['candidate_index'];seed=row['seed'];key=(i,seed)
        if row['generation']!=generation or not isinstance(i,int) or not 0<=i<POPULATION or seed not in OPTIMIZATION_SEEDS or key in indexed:raise ValueError('Wrong,duplicate or cross-generation condition')
        if not np.array_equal(np.asarray(row['knots'],dtype=np.float32),p[i]):raise ValueError('Condition was generated by another candidate')
        indexed[key]=row
    pairs=[[indexed[(i,seed)] for seed in OPTIMIZATION_SEEDS] for i in range(POPULATION)]
    scores=[paired_rank(pair,horizon,mask) for pair in pairs]
    return pairs,scores

class PairedCEM:
    def __init__(self,mask,prior,seed=410032):
        self.mask=active_mask(mask).astype(np.float32);self.active=np.repeat(self.mask,26);self.rng=np.random.default_rng(seed)
        prior=np.asarray(prior,dtype=np.float32)
        if prior.shape!=(4,52) or not np.isfinite(prior).all() or abs(prior).max()>2 or (prior*(1-self.active)).any():raise ValueError('Invalid frozen sixth controller')
        self.prior=prior.copy();self.mean=prior.astype(np.float64).copy();self.std=np.full((4,52),.6)
        self.best=prior.copy();self.best_score=None;self.generations=0
    def population(self):
        if self.generations>=MAX_GENERATIONS:raise ValueError('Generation limit reached')
        p=(np.clip(self.rng.normal(self.mean,self.std,size=(POPULATION,4,52)),-2,2)*self.active).astype(np.float32)
        p[0]=0;p[1]=self.prior # Fixed baseline and frozen sixth anchor as proposed.
        return p
    def update(self,population,rows,horizon,generation):
        if generation!=self.generations:raise ValueError('Generation sequence is not continuous')
        pairs,scores=pair_generation(population,rows,horizon,self.mask,generation)
        order=sorted(range(POPULATION),key=lambda i:scores[i],reverse=True);top=order[0]
        # Every validation above precedes all mutation; partial/mixed seed sets
        # cannot update the mean,variance,best score or generation count.
        if self.best_score is None or scores[top]>self.best_score:self.best=np.array(population[top],copy=True);self.best_score=scores[top]
        elite=np.asarray(population)[order[:4]].astype(np.float64)
        self.mean=.5*self.mean+.5*elite.mean(0);self.std=np.clip(.5*self.std+.5*elite.std(0),.1,1.)
        self.generations+=1
        return dict(best_index=top,best_score=list(self.best_score),elite_indices=order[:4],both_seed_regular_candidates=[i for i,pair in enumerate(pairs) if all(r['regular_success'] for r in pair)])

